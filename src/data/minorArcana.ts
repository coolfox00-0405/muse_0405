function buildSuitCards(suit: TarotSuit, seeds: MinorCardSeed[]): TarotCard[] {
  const meta = SUIT_META[suit];
  return seeds.map((seed, idx) => ({
    id: `minor-${suit}-${String(idx + 1).padStart(2, '0')}`,
    arcana: 'minor',
    suit,
    suitTheme: meta.theme,
    arcanaNumber: `${meta.nameKo} ${seed.rankNum}`,
    nameKo: `${meta.nameKo} ${seed.rankKo}`,
    nameEn: `${seed.rankEn} of ${meta.nameEn}`,
    keywords: seed.keywords,
    insight: seed.insight,
    reflectionQuestion: seed.question,
    gentleAction: seed.action,
    meaningGuide: seed.guide,
    symbolKey: suit,
    frontImageUrl:
      seed.imageUrl ?? `/src/assets/images/${suit}_${seed.rankEn.toLowerCase()}.webp`,
    backImageUrl: BACK_IMAGE,
  }));
}

